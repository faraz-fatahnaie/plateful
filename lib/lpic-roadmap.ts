import type { StudySession } from "./playlist-study";

function session(date: string, episodes: string, watchTime: string, module: string): StudySession {
  const [minutes, seconds] = watchTime.split(":").map(Number);
  const watchSeconds = minutes * 60 + seconds;
  return {
    id: `session-${date}`,
    date,
    videoIds: episodes.split(",").map((episode) => `ep-${episode.trim().padStart(3, "0")}`),
    plannedMinutes: Math.ceil(watchSeconds / 60),
    watchSeconds,
    module,
    status: "planned",
  };
}

